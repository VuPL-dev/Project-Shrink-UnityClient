using System.Collections.Generic;
using UnityEngine;
using UnityEngine.UI;

/// <summary>
/// Quản lý Bật / Tắt giao diện Túi đồ (Inventory UI) và đồng bộ trực tiếp với Database MongoDB.
/// Phím tắt mặc định: 'I' hoặc 'B' hoặc 'Tab'.
/// Nếu chưa dựng Canvas sẵn trong Inspector, script sẽ TỰ ĐỘNG SINH GIAO DIỆN (Auto-Generate UI) khi chạy!
/// </summary>
public class InventoryUIController : MonoBehaviour
{
    public static InventoryUIController Instance { get; private set; }

    [Header("Keyboard Shortcuts")]
    [Tooltip("Phím bấm để Bật/Tắt túi đồ")]
    public KeyCode toggleKey = KeyCode.I;
    public KeyCode alternateKey = KeyCode.Tab;

    [Header("UI References (Tự động tạo nếu để trống)")]
    public GameObject inventoryPanel;
    public Transform  slotsContainer;
    public Text       capacityText;
    public Text       statusText;

    private bool isInventoryOpen = false;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.AfterSceneLoad)]
    private static void AutoInitInventorySystem()
    {
        if (Instance == null && Object.FindObjectsByType<InventoryUIController>(FindObjectsSortMode.None).Length == 0)
        {
            GameObject autoInv = new GameObject("InventorySystem_AutoGenerated");
            autoInv.AddComponent<InventoryUIController>();
            DontDestroyOnLoad(autoInv);
        }
    }

    private void Awake()
    {
        if (Instance == null) Instance = this;
        else Destroy(gameObject);
    }

    private void Start()
    {
        // Nếu chưa có NetworkManager trong Scene, tự động tạo để gọi API
        if (InventoryNetworkManager.Instance == null)
        {
            GameObject netObj = new GameObject("InventoryNetworkManager");
            netObj.AddComponent<InventoryNetworkManager>();
        }

        // Tự động sinh giao diện uGUI nếu Inspector chưa gán Panel
        if (inventoryPanel == null)
        {
            BuildRuntimeInventoryUI();
        }

        // Mặc định ban đầu ẩn túi đồ
        if (inventoryPanel != null)
        {
            inventoryPanel.SetActive(false);
        }

        // Lắng nghe sự kiện dữ liệu túi đồ thay đổi từ server
        if (InventoryNetworkManager.Instance != null)
        {
            InventoryNetworkManager.Instance.OnInventoryChanged += UpdateUI;
            InventoryNetworkManager.Instance.OnItemUsed += HandleItemUsed;
        }
    }

    private void OnDestroy()
    {
        if (InventoryNetworkManager.Instance != null)
        {
            InventoryNetworkManager.Instance.OnInventoryChanged -= UpdateUI;
            InventoryNetworkManager.Instance.OnItemUsed -= HandleItemUsed;
        }
    }

    private void Update()
    {
        // Lắng nghe phím bấm bật/tắt túi đồ
        if (Input.GetKeyDown(toggleKey) || Input.GetKeyDown(alternateKey))
        {
            ToggleInventory();
        }
        else if (isInventoryOpen && Input.GetKeyDown(KeyCode.Escape))
        {
            CloseInventory();
        }
    }

    /// <summary>
    /// Bật hoặc tắt túi đồ
    /// </summary>
    public void ToggleInventory()
    {
        if (isInventoryOpen)
        {
            CloseInventory();
        }
        else
        {
            OpenInventory();
        }
    }

    public void OpenInventory()
    {
        isInventoryOpen = true;
        if (inventoryPanel != null) inventoryPanel.SetActive(true);

        // Hiển thị con trỏ chuột để thao tác với túi đồ
        Cursor.lockState = CursorLockMode.None;
        Cursor.visible = true;

        SetStatus("Đang đồng bộ dữ liệu với Database...", Color.yellow);

        // Gọi API tải dữ liệu mới nhất từ MongoDB
        if (InventoryNetworkManager.Instance != null)
        {
            InventoryNetworkManager.Instance.FetchInventory(
                onSuccess: (data) => SetStatus("Đã đồng bộ thành công!", Color.green),
                onError: (err) => SetStatus("Lỗi kết nối: " + err, Color.red)
            );
        }
    }

    public void CloseInventory()
    {
        isInventoryOpen = false;
        if (inventoryPanel != null) inventoryPanel.SetActive(false);

        // Ẩn lại con trỏ chuột về trạng thái chơi game (nếu cần)
        // Cursor.lockState = CursorLockMode.Locked;
        // Cursor.visible = false;
    }

    /// <summary>
    /// Vẽ lại toàn bộ các ô đồ khi nhận được dữ liệu mới từ Database
    /// </summary>
    private void UpdateUI(InventoryData data)
    {
        if (data == null || slotsContainer == null) return;

        // Cập nhật text sức chứa
        if (capacityText != null)
        {
            capacityText.text = $"Sức chứa: {data.items.Count}/{data.capacity} | Trọng lượng: {data.currentWeight:F1}/{data.maxWeight} kg";
        }

        // Xóa các slot cũ
        foreach (Transform child in slotsContainer)
        {
            Destroy(child.gameObject);
        }

        if (data.items.Count == 0)
        {
            SetStatus("Túi đồ hiện đang trống.", Color.gray);
            return;
        }

        // Tạo từng slot hiển thị món đồ
        foreach (var item in data.items)
        {
            CreateSlotUI(item);
        }
    }

    private void CreateSlotUI(InventoryItemDto item)
    {
        GameObject slotObj = new GameObject($"Slot_{item.itemId}", typeof(RectTransform), typeof(Image));
        slotObj.transform.SetParent(slotsContainer, false);
        Image slotBg = slotObj.GetComponent<Image>();
        slotBg.color = new Color(0.18f, 0.22f, 0.28f, 0.9f); // Nền xám xanh

        // Text tên item và số lượng
        GameObject textObj = new GameObject("Text", typeof(RectTransform), typeof(Text));
        textObj.transform.SetParent(slotObj.transform, false);
        Text label = textObj.GetComponent<Text>();
        label.font = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");
        label.fontSize = 14;
        label.alignment = TextAnchor.MiddleCenter;
        label.color = Color.white;
        label.text = $"{FormatItemName(item.itemId)}\nx{item.quantity}";
        RectTransform textRt = textObj.GetComponent<RectTransform>();
        textRt.anchorMin = Vector2.zero;
        textRt.anchorMax = new Vector2(1, 0.65f);
        textRt.offsetMin = Vector2.zero;
        textRt.offsetMax = Vector2.zero;

        // Nút "Dùng" (Use)
        GameObject btnObj = new GameObject("BtnUse", typeof(RectTransform), typeof(Image), typeof(Button));
        btnObj.transform.SetParent(slotObj.transform, false);
        Image btnImg = btnObj.GetComponent<Image>();
        btnImg.color = new Color(0.1f, 0.65f, 0.35f, 1f); // Nút màu xanh lá
        RectTransform btnRt = btnObj.GetComponent<RectTransform>();
        btnRt.anchorMin = new Vector2(0.1f, 0.08f);
        btnRt.anchorMax = new Vector2(0.9f, 0.35f);
        btnRt.offsetMin = Vector2.zero;
        btnRt.offsetMax = Vector2.zero;

        GameObject btnTextObj = new GameObject("BtnText", typeof(RectTransform), typeof(Text));
        btnTextObj.transform.SetParent(btnObj.transform, false);
        Text btnText = btnTextObj.GetComponent<Text>();
        btnText.font = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");
        btnText.fontSize = 12;
        btnText.alignment = TextAnchor.MiddleCenter;
        btnText.color = Color.white;
        btnText.text = "Dùng";
        RectTransform btnTextRt = btnTextObj.GetComponent<RectTransform>();
        btnTextRt.anchorMin = Vector2.zero;
        btnTextRt.anchorMax = Vector2.one;
        btnTextRt.offsetMin = Vector2.zero;
        btnTextRt.offsetMax = Vector2.zero;

        Button btn = btnObj.GetComponent<Button>();
        string currentItemId = item.itemId;
        btn.onClick.AddListener(() =>
        {
            SetStatus($"Đang dùng {FormatItemName(currentItemId)}...", Color.yellow);
            InventoryNetworkManager.Instance.UseItem(currentItemId, 1,
                onSuccess: (updated) => SetStatus($"Đã dùng 1 {FormatItemName(currentItemId)} thành công!", Color.green),
                onError: (err) => SetStatus("Không thể dùng: " + err, Color.red)
            );
        });
    }

    private void HandleItemUsed(string itemId, int quantity)
    {
        Debug.Log($"[InventoryUI] Đã kích hoạt hiệu ứng sử dụng item: {itemId} x{quantity}");
        // Có thể cộng máu cho player tại đây nếu itemId == "health_syringe"
    }

    private string FormatItemName(string itemId)
    {
        switch (itemId)
        {
            case "health_syringe": return "Ống Tiêm Máu";
            case "item_kim_khau":  return "Kim Khâu Tí Hon";
            case "item_so_tay":    return "Sổ Ghi Chép";
            case "lab_keycard":    return "Thẻ Từ Phòng Mổ";
            case "nano_blade":     return "Dao Nano";
            default: return itemId;
        }
    }

    private void SetStatus(string msg, Color color)
    {
        if (statusText != null)
        {
            statusText.text = msg;
            statusText.color = color;
        }
    }

    /// <summary>
    /// Tự động sinh giao diện Canvas UI hoàn chỉnh nếu chưa có sẵn
    /// </summary>
    private void BuildRuntimeInventoryUI()
    {
        // 1. Tạo Canvas
        Canvas canvas = FindObjectOfType<Canvas>();
        if (canvas == null)
        {
            GameObject canvasObj = new GameObject("InventoryCanvas", typeof(Canvas), typeof(CanvasScaler), typeof(GraphicRaycaster));
            canvas = canvasObj.GetComponent<Canvas>();
            canvas.renderMode = RenderMode.ScreenSpaceOverlay;
            CanvasScaler scaler = canvasObj.GetComponent<CanvasScaler>();
            scaler.uiScaleMode = CanvasScaler.ScaleMode.ScaleWithScreenSize;
            scaler.referenceResolution = new Vector2(1920, 1080);
        }

        // Đảm bảo có EventSystem để bấm được chuột
        if (FindObjectOfType<UnityEngine.EventSystems.EventSystem>() == null)
        {
            new GameObject("EventSystem", typeof(UnityEngine.EventSystems.EventSystem), typeof(UnityEngine.EventSystems.StandaloneInputModule));
        }

        // 2. Main Panel
        inventoryPanel = new GameObject("InventoryPanel", typeof(RectTransform), typeof(Image));
        inventoryPanel.transform.SetParent(canvas.transform, false);
        Image panelBg = inventoryPanel.GetComponent<Image>();
        panelBg.color = new Color(0.08f, 0.10f, 0.14f, 0.95f); // Nền tối cyberpunk
        RectTransform panelRt = inventoryPanel.GetComponent<RectTransform>();
        panelRt.sizeDelta = new Vector2(650, 520);
        panelRt.anchoredPosition = Vector2.zero;

        Font builtinFont = Resources.GetBuiltinResource<Font>("LegacyRuntime.ttf");

        // 3. Header Title
        GameObject titleObj = new GameObject("TitleText", typeof(RectTransform), typeof(Text));
        titleObj.transform.SetParent(inventoryPanel.transform, false);
        Text title = titleObj.GetComponent<Text>();
        title.font = builtinFont;
        title.fontSize = 22;
        title.fontStyle = FontStyle.Bold;
        title.alignment = TextAnchor.MiddleCenter;
        title.color = new Color(0.2f, 0.8f, 1f, 1f); // Xanh cyan
        title.text = "🎒 TÚI ĐỒ (INVENTORY) - [PHÍM 'I' ĐỂ ĐÓNG]";
        RectTransform titleRt = titleObj.GetComponent<RectTransform>();
        titleRt.anchorMin = new Vector2(0, 0.9f);
        titleRt.anchorMax = new Vector2(1, 1f);
        titleRt.offsetMin = Vector2.zero;
        titleRt.offsetMax = Vector2.zero;

        // 4. Capacity & Weight Text
        GameObject capObj = new GameObject("CapacityText", typeof(RectTransform), typeof(Text));
        capObj.transform.SetParent(inventoryPanel.transform, false);
        capacityText = capObj.GetComponent<Text>();
        capacityText.font = builtinFont;
        capacityText.fontSize = 14;
        capacityText.alignment = TextAnchor.MiddleLeft;
        capacityText.color = Color.white;
        capacityText.text = "Sức chứa: 0/20";
        RectTransform capRt = capObj.GetComponent<RectTransform>();
        capRt.anchorMin = new Vector2(0.05f, 0.82f);
        capRt.anchorMax = new Vector2(0.95f, 0.88f);
        capRt.offsetMin = Vector2.zero;
        capRt.offsetMax = Vector2.zero;

        // 5. Grid Container
        GameObject gridObj = new GameObject("GridSlots", typeof(RectTransform), typeof(GridLayoutGroup));
        gridObj.transform.SetParent(inventoryPanel.transform, false);
        slotsContainer = gridObj.transform;
        GridLayoutGroup grid = gridObj.GetComponent<GridLayoutGroup>();
        grid.cellSize = new Vector2(110, 110);
        grid.spacing = new Vector2(12, 12);
        grid.padding = new RectOffset(10, 10, 10, 10);
        grid.startAxis = GridLayoutGroup.Axis.Horizontal;
        grid.constraint = GridLayoutGroup.Constraint.FixedColumnCount;
        grid.constraintCount = 5;
        RectTransform gridRt = gridObj.GetComponent<RectTransform>();
        gridRt.anchorMin = new Vector2(0.05f, 0.15f);
        gridRt.anchorMax = new Vector2(0.95f, 0.82f);
        gridRt.offsetMin = Vector2.zero;
        gridRt.offsetMax = Vector2.zero;

        // 6. Status Text
        GameObject statusObj = new GameObject("StatusText", typeof(RectTransform), typeof(Text));
        statusObj.transform.SetParent(inventoryPanel.transform, false);
        statusText = statusObj.GetComponent<Text>();
        statusText.font = builtinFont;
        statusText.fontSize = 13;
        statusText.alignment = TextAnchor.MiddleCenter;
        statusText.color = Color.gray;
        statusText.text = "Nhấn 'I' để mở/đóng túi đồ.";
        RectTransform statusRt = statusObj.GetComponent<RectTransform>();
        statusRt.anchorMin = new Vector2(0.05f, 0.02f);
        statusRt.anchorMax = new Vector2(0.75f, 0.12f);
        statusRt.offsetMin = Vector2.zero;
        statusRt.offsetMax = Vector2.zero;

        // 7. Close Button (X)
        GameObject closeObj = new GameObject("BtnClose", typeof(RectTransform), typeof(Image), typeof(Button));
        closeObj.transform.SetParent(inventoryPanel.transform, false);
        Image closeImg = closeObj.GetComponent<Image>();
        closeImg.color = new Color(0.8f, 0.2f, 0.2f, 1f);
        RectTransform closeRt = closeObj.GetComponent<RectTransform>();
        closeRt.anchorMin = new Vector2(0.82f, 0.04f);
        closeRt.anchorMax = new Vector2(0.96f, 0.12f);
        closeRt.offsetMin = Vector2.zero;
        closeRt.offsetMax = Vector2.zero;

        GameObject closeTextObj = new GameObject("CloseText", typeof(RectTransform), typeof(Text));
        closeTextObj.transform.SetParent(closeObj.transform, false);
        Text closeText = closeTextObj.GetComponent<Text>();
        closeText.font = builtinFont;
        closeText.fontSize = 14;
        closeText.alignment = TextAnchor.MiddleCenter;
        closeText.color = Color.white;
        closeText.text = "Đóng";
        RectTransform closeTextRt = closeTextObj.GetComponent<RectTransform>();
        closeTextRt.anchorMin = Vector2.zero;
        closeTextRt.anchorMax = Vector2.one;
        closeTextRt.offsetMin = Vector2.zero;
        closeTextRt.offsetMax = Vector2.zero;

        closeObj.GetComponent<Button>().onClick.AddListener(CloseInventory);
    }
}
